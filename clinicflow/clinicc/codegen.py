import json
import re

from .ir import Const, BINOPS, fmt

ASM = {"+": "ADD", "-": "SUB", "*": "MUL", "/": "DIV", "<": "CMPLT", ">": "CMPGT",
       "<=": "CMPLE", ">=": "CMPGE", "==": "CMPEQ", "!=": "CMPNE", "and": "AND", "or": "OR"}


def to_assembly(code):
    out = ["; ClinicalVM assembly (generated by the ClinicalScript compiler)", "        ENTER"]
    for i in code:
        if i.op == "label":
            out.append(f"{i.res}:")
            continue
        if i.op == "assign":
            s = f"MOV    {i.res}, {fmt(i.arg1)}"
        elif i.op in ASM:
            s = f"{ASM[i.op]:<7}{i.res}, {fmt(i.arg1)}, {fmt(i.arg2)}"
        elif i.op == "not":
            s = f"NOT    {i.res}, {fmt(i.arg1)}"
        elif i.op == "jz":
            s = f"JZ     {fmt(i.arg1)}, {i.res}"
        elif i.op == "jmp":
            s = f"JMP    {i.res}"
        elif i.op == "order":
            s = f'ORDER  "{i.arg1}"'
        elif i.op == "alert":
            s = f'ALERT  "{i.arg1}"'
        else:
            s = f'RX     "{i.arg1}", {fmt(i.arg2)}, {i.res}'
        out.append("        " + s)
    out.append("        HALT")
    return "\n".join(out)


def _py(x):
    if isinstance(x, Const):
        v = x.value
        if isinstance(v, float) and v == int(v):
            return repr(int(v))
        return repr(v)
    return x if re.fullmatch(r"t\d+", x) else "v_" + x


def to_python(code):
    labels = {i.res: n for n, i in enumerate(code) if i.op == "label"}
    L = ["# Generated by the ClinicalScript compiler (state-machine form)",
         "def run_workflow():", "    actions = []", "    pc = 0",
         f"    while pc < {len(code)}:"]
    for n, i in enumerate(code):
        L.append(f"        if pc == {n}:")
        b = []
        if i.op == "assign":
            b.append(f"{_py(i.res)} = {_py(i.arg1)}")
        elif i.op in BINOPS:
            b.append(f"{_py(i.res)} = {_py(i.arg1)} {i.op} {_py(i.arg2)}")
        elif i.op == "not":
            b.append(f"{_py(i.res)} = not {_py(i.arg1)}")
        elif i.op == "jz":
            b += [f"if not {_py(i.arg1)}:", f"    pc = {labels[i.res]}", "    continue"]
        elif i.op == "jmp":
            b += [f"pc = {labels[i.res]}", "continue"]
        elif i.op == "label":
            b.append("pass")
        elif i.op == "order":
            b.append(f"actions.append(('ORDER', {i.arg1!r}))")
        elif i.op == "alert":
            b.append(f"actions.append(('ALERT', {i.arg1!r}))")
        elif i.op == "rx":
            b.append(f"actions.append(('PRESCRIBE', {i.arg1!r} + ' ' + format({_py(i.arg2)}, 'g') + ' ' + {i.res!r}))")
        b.append(f"pc = {n + 1}")
        L += ["            " + x for x in b]
    L += ["    return actions", "", "",
          'if __name__ == "__main__":',
          "    for kind, text in run_workflow():",
          "        print(kind, '-', text)"]
    return "\n".join(L)


def execute(code):
    labels = {i.res: n for n, i in enumerate(code) if i.op == "label"}
    env, acts, pc = {}, [], 0

    def val(x):
        return x.value if isinstance(x, Const) else env[x]

    try:
        while pc < len(code):
            i = code[pc]
            pc += 1
            op = i.op
            if op == "assign":
                env[i.res] = val(i.arg1)
            elif op in BINOPS:
                env[i.res] = BINOPS[op](val(i.arg1), val(i.arg2))
            elif op == "not":
                env[i.res] = not val(i.arg1)
            elif op == "jz":
                if not val(i.arg1):
                    pc = labels[i.res]
            elif op == "jmp":
                pc = labels[i.res]
            elif op == "order":
                acts.append(("ORDER", i.arg1))
            elif op == "alert":
                acts.append(("ALERT", i.arg1))
            elif op == "rx":
                acts.append(("PRESCRIBE", f"{i.arg1} {format(val(i.arg2), 'g')} {i.res}"))
    except ZeroDivisionError:
        acts.append(("ERROR", "Division by zero during execution"))
    return acts


def to_orders_json(actions):
    entries = []
    for kind, text in actions:
        if kind == "ORDER":
            entries.append({"resourceType": "ServiceRequest", "status": "active",
                            "intent": "order", "code": {"text": text}})
        elif kind == "PRESCRIBE":
            entries.append({"resourceType": "MedicationRequest", "status": "draft",
                            "intent": "proposal", "medicationCodeableConcept": {"text": text}})
        elif kind == "ALERT":
            entries.append({"resourceType": "Flag", "status": "active", "code": {"text": text}})
    return json.dumps({"resourceType": "Bundle", "type": "collection",
                       "note": "Simplified FHIR-style output for teaching only",
                       "entry": entries}, indent=2)
